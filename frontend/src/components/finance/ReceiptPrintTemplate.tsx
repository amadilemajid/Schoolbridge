import React from 'react';

interface ReceiptPrintTemplateProps {
  payment: {
    studentName: string;
    studentId: string;
    amount: number;
    method: string;
    date: string;
    receiptNumber: string;
    recordedBy: string;
  };
  school?: {
    name?: string;
    address?: string;
    phone?: string;
  };
}

export const ReceiptPrintTemplate: React.FC<ReceiptPrintTemplateProps> = ({ payment, school }) => {
  const schoolName = school?.name || 'School';
  const schoolAddress = school?.address || '';
  const schoolPhone = school?.phone || '';

  return (
    <div className="hidden print:block font-mono text-black bg-white p-4 max-w-[80mm] text-[12px] leading-tight mx-auto" id="printable-receipt">
      <div className="text-center mb-4">
        <h1 className="font-bold text-[16px] uppercase">{schoolName}</h1>
        {schoolAddress && <p>{schoolAddress}</p>}
        {schoolPhone && <p>Tel: {schoolPhone}</p>}
        <p className="font-bold mt-2 border-b border-black border-dashed pb-2">OFFICIAL RECEIPT</p>
      </div>

      <div className="space-y-2 mb-4">
        <div className="flex justify-between">
          <span>Date:</span>
          <span>{payment.date}</span>
        </div>
        <div className="flex justify-between">
          <span>Receipt No:</span>
          <span>{payment.receiptNumber}</span>
        </div>
        <div className="flex justify-between">
          <span>Student ID:</span>
          <span>{payment.studentId}</span>
        </div>
        <div className="flex justify-between">
          <span>Name:</span>
          <span className="font-bold">{payment.studentName}</span>
        </div>
      </div>

      <div className="border-t border-b border-black border-dashed py-2 mb-4">
        <div className="flex justify-between font-bold text-[14px]">
          <span>TOTAL PAID:</span>
          <span>UGX {payment.amount.toLocaleString()}</span>
        </div>
        <div className="flex justify-between mt-1">
          <span>Method:</span>
          <span className="uppercase">{payment.method}</span>
        </div>
      </div>

      <div className="text-center mt-6">
        <p>Served by: {payment.recordedBy}</p>
        <p className="mt-4 text-[10px] italic">Thank you for your payment!</p>
        <p className="text-[10px]">Generated by SchoolBridge ERP</p>
      </div>
    </div>
  );
};
